import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const input = process.argv.find((x, i) => i > 1 && !x.startsWith("--")) ?? path.join(root, "schema/introspection.json");
const document = JSON.parse(fs.readFileSync(input, "utf8"));
const schema = document.data?.__schema ?? document.__schema ?? document;
const reserved = new Set("ado as case class data derive do else false forall foreign hiding if import in infix infixl infixr instance kind let module newtype nominal of phantom representational role then true type where".split(" "));
const ident = n => reserved.has(n) ? `${n}_` : n;
const cap = n => n[0].toUpperCase() + n.slice(1);
const base = t => t.ofType ? base(t.ofType) : t;
const unnull = t => t.kind === "NON_NULL" ? t.ofType : t;
const gqlType = t => t.kind === "NON_NULL" ? `${gqlType(t.ofType)}!` : t.kind === "LIST" ? `[${gqlType(t.ofType)}]` : t.name;
const builtin = { String: "String", Int: "Int", Float: "Number", Boolean: "Boolean" };
const types = schema.types.filter(t => !t.name.startsWith("_")).sort((a,b)=>a.name.localeCompare(b.name, "en"));
const inputs = new Map(types.filter(t => t.kind === "INPUT_OBJECT").map(t => [t.name, t]));
const recursiveInput = name => {
  const visit = (current, seen) => inputs.get(current)?.inputFields.some(f => {
    const next = base(f.type).name;
    return next === name || (!seen.has(next) && visit(next, new Set([...seen, next])));
  }) ?? false;
  return visit(name, new Set([name]));
};
const known = new Set(types.map(t => t.name));
const objectKind = k => k === "OBJECT" || k === "INTERFACE";
const psType = (t, prefix = "T.", expected = null) => {
  if (t.kind !== "NON_NULL") return `(Maybe ${psNonNull(t, prefix, expected)})`;
  return psNonNull(t.ofType, prefix, expected);
};
const psNonNull = (t, prefix, expected) => {
  if (t.kind === "LIST") return `(Array ${psType(t.ofType, prefix, expected)})`;
  return expected ? `${prefix}${expected}` : builtin[t.name] ?? `${prefix}${t.name}`;
};
const expectedType = arg => {
  const d = arg.directives?.find(d => d.name === "expectedType");
  const v = d?.args?.find(a => a.name === "name")?.value;
  return v ? JSON.parse(v) : null;
};
const docs = text => text ? text.split("\n").map(line => `-- | ${line}`.trimEnd()).join("\n") + "\n" : "";
const files = new Map();
const banner = "-- Generated by scripts/generate.mjs. Do not edit.\n";
let declarations = [];
for (const t of types) {
  if (objectKind(t.kind)) declarations.push(`${docs(t.description)}foreign import data ${t.name}Tag :: Type\ntype ${t.name} = Object ${t.name}Tag\ninstance objectType${t.name} :: IsObject ${t.name}Tag where\n  objectTypeName _ = ${JSON.stringify(t.name)}\n`);
  else if (t.kind === "SCALAR" && !builtin[t.name]) {
    const repr = t.name === "Void" ? "Json" : "String";
    declarations.push(`${docs(t.description)}newtype ${t.name} = ${t.name} ${repr}\nderive instance eq${t.name} :: Eq ${t.name}\nderive newtype instance encode${t.name} :: EncodeJson ${t.name}\nderive newtype instance decode${t.name} :: DecodeJson ${t.name}\n`);
  } else if (t.kind === "ENUM") {
    const normalized = v => v.name.split("_").map(w => cap(w === w.toUpperCase() ? w.toLowerCase() : w)).join("");
    const ctor = v => t.name + (t.enumValues.filter(x => normalized(x) === normalized(v)).length > 1 ? v.name : normalized(v));
    declarations.push(`${docs(t.description)}data ${t.name} = ${t.enumValues.map(ctor).join(" | ")}\nderive instance eq${t.name} :: Eq ${t.name}\nderive instance ord${t.name} :: Ord ${t.name}\ninstance show${t.name} :: Show ${t.name} where\n  show = case _ of\n${t.enumValues.map(v=>`    ${ctor(v)} -> ${JSON.stringify(v.name)}`).join("\n")}\ninstance encode${t.name} :: EncodeJson ${t.name} where\n  encodeJson = encodeJson <<< show\ninstance decode${t.name} :: DecodeJson ${t.name} where\n  decodeJson value = do\n    name <- decodeJson value\n    case name of\n${t.enumValues.map(v=>`      ${JSON.stringify(v.name)} -> Right ${ctor(v)}`).join("\n")}\n      _ -> Left (TypeMismatch ${JSON.stringify(t.name)})\n`);
  } else if (t.kind === "INPUT_OBJECT") {
    const recursive = recursiveInput(t.name);
    declarations.push(`${docs(t.description)}${recursive ? "newtype" : "type"} ${t.name} =${recursive ? ` ${t.name}` : ""}\n  { ${t.inputFields.map(f=>`${JSON.stringify(f.name)} :: ${psType(f.type, "")}`).join("\n  , ")}\n  }\n${recursive ? `instance encode${t.name} :: EncodeJson ${t.name} where\n  encodeJson (${t.name} value) = encodeJson value\ninstance decode${t.name} :: DecodeJson ${t.name} where\n  decodeJson value = ${t.name} <$> decodeJson value\n` : ""}`);
  } else if (t.kind !== "SCALAR") throw new Error(`Unsupported schema kind ${t.kind}`);
  if (t.kind === "ENUM" || t.kind === "SCALAR" && !builtin[t.name]) {
    declarations.push(`instance moduleValue${t.name} :: V.DaggerValue ${t.name} where\n  valueType _ = V.${t.kind === "ENUM" ? "EnumType" : "ScalarType"} ${JSON.stringify(t.name)}\n  decodeValue _ = V.decodeJSON\n  encodeValue = pure <<< encodeJson\n`);
  }
}
files.set("Types.purs", banner + `module Dagger.Types where\n\nimport Prelude hiding (Void)\nimport Data.Argonaut.Core (Json)\nimport Data.Argonaut.Decode (class DecodeJson, decodeJson)\nimport Data.Argonaut.Decode.Error (JsonDecodeError(..))\nimport Data.Argonaut.Encode (class EncodeJson, encodeJson)\nimport Data.Either (Either(..))\nimport Data.Maybe (Maybe)\nimport Dagger.Internal.Runtime (Object)\nimport Dagger.Module.Value (class IsObject)\nimport Dagger.Module.Value as V\n\n` + declarations.join("\n"));
let fieldCount = 0;
for (const t of types.filter(t => objectKind(t.kind))) {
  const functions = [], exports = [];
  const imports = new Set();
  for (const f of [...t.fields].sort((a,b)=>a.name.localeCompare(b.name, "en"))) {
    if (!known.has(base(f.type).name) || f.args.some(a=>!known.has(base(a.type).name))) continue;
    const name = ident(f.name), required = f.args.filter(a=>a.type.kind === "NON_NULL" && a.defaultValue == null), opts = f.args.filter(a=>!required.includes(a));
    const argType = a => psNonNull(unnull(a.type), "T.", expectedType(a));
    const args = f.args.map(a=> {
      const expected = expectedType(a);
      let fn = expected ? unnull(a.type).kind === "LIST" ? "objectsArgument" : "objectArgument" : "argument";
      const call = `R.${fn} ${JSON.stringify(a.name)} ${JSON.stringify(gqlType(a.type))}`;
      return opts.includes(a) ? `R.optional (${call}) opts.${ident(a.name)}` : `${call} arg${cap(a.name)}`;
    });
    const b = base(f.type), inner = unnull(f.type);
    let result = psType(f.type), operation = "R.scalar";
    if (objectKind(b.kind)) {
      if (inner.kind === "LIST") {
        if (f.type.kind !== "NON_NULL" || inner.ofType.kind !== "NON_NULL") throw new Error(`Nullable object list unsupported: ${t.name}.${f.name}`);
        operation = `R.objectList ${JSON.stringify(b.name)}`;
        result = `Aff (Array T.${b.name})`;
      } else if (f.type.kind !== "NON_NULL") { operation = `R.nullableObject ${JSON.stringify(b.name)}`; result = `Aff (Maybe T.${b.name})`; }
      else { operation = "R.select"; result = `T.${b.name}`; }
    } else result = `Aff ${result}`;
    if (result.includes("Aff")) imports.add("import Effect.Aff (Aff)");
    if (result.includes("Maybe") || required.some(a=>argType(a).includes("Maybe"))) imports.add("import Data.Maybe (Maybe)");
    const signatures = required.map(argType);
    const params = required.map(a=>`arg${cap(a.name)}`);
    const comment = docs(f.description) + (f.isDeprecated ? docs(`Deprecated: ${f.deprecationReason ?? "Deprecated by the engine."}`) : "");
    exports.push(name);
    if (opts.length) {
      imports.add("import Data.Maybe (Maybe(..))");
      const optsType = `${cap(f.name)}Opts`, defaultName = `default${cap(f.name)}Opts`, withName = `${f.name}With`;
      exports.push(withName, optsType, defaultName);
      functions.push(`type ${optsType} =\n  { ${opts.map(a=>`${ident(a.name)} :: Maybe ${argType(a)}`).join("\n  , ")}\n  }\n\n${defaultName} :: ${optsType}\n${defaultName} =\n  { ${opts.map(a=>`${ident(a.name)}: Nothing`).join("\n  , ")}\n  }\n`);
      functions.push(`${comment}${name} :: ${[...signatures,`T.${t.name}`,result].join(" -> ")}\n${name}${params.length ? " " + params.join(" ") : ""} = ${withName} ${[...params, defaultName].join(" ")}\n`);
      functions.push(`${comment}${withName} :: ${[...signatures,optsType,`T.${t.name}`,result].join(" -> ")}\n${withName} ${[...params,"opts"].join(" ")} = ${operation} ${JSON.stringify(f.name)} [${args.join(", ")}]\n`);
    } else functions.push(`${comment}${name} :: ${[...signatures,`T.${t.name}`,result].join(" -> ")}\n${name}${params.length ? " " + params.join(" ") : ""} = ${operation} ${JSON.stringify(f.name)} [${args.join(", ")}]\n`);
    fieldCount++;
  }
  // Explicit casts are typed inline fragments, useful for Query.node results.
  if (t.kind === "INTERFACE") for (const p of t.possibleTypes ?? []) {
    if (!known.has(p.name)) continue;
    const name = `as${p.name}`; exports.push(name);
    functions.push(`${name} :: T.${t.name} -> T.${p.name}\n${name} = R.fragment ${JSON.stringify(p.name)}\n`);
  }
  files.set(`${t.name}.purs`, banner + `module Dagger.${t.name}\n  ( ${exports.join("\n  , ")}\n  ) where\n\n${[...imports].sort().join("\n")}\nimport Dagger.Internal.Runtime as R\nimport Dagger.Types as T\n\n` + functions.join("\n"));
}
for (const [name, content] of files) files.set(name, content.includes("import Data.Maybe (Maybe(..))") ? content.replace("import Data.Maybe (Maybe)\n", "") : content);
const dir = path.join(root, "src/Dagger");
fs.mkdirSync(dir, {recursive:true});
for (const entry of fs.readdirSync(dir)) {
  const target = path.join(dir, entry);
  if (entry.endsWith(".purs") && !files.has(entry) && fs.readFileSync(target, "utf8").startsWith(banner)) {
    if (check) throw new Error(`Stale generated file: ${entry}`);
    fs.unlinkSync(target);
  }
}
for (const [name, content] of files) {
  const target = path.join(dir,name);
  if (check) { if (!fs.existsSync(target) || fs.readFileSync(target,"utf8") !== content) throw new Error(`Generated file differs: ${name}`); }
  else {
    if (fs.existsSync(target) && !fs.readFileSync(target,"utf8").startsWith(banner)) throw new Error(`Schema name collides with handwritten module: ${name}`);
    fs.writeFileSync(target,content);
  }
}
console.log(`${check ? "Checked" : "Generated"} ${files.size} modules, ${fieldCount} fields.`);
